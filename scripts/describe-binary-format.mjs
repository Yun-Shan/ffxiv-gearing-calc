const seen = new Map();
const blocks = [];
function describe(schema, path) {
  if (schema.kind === "optional")
    return `${describe(schema.value, path)}（可选）`;
  if (schema.kind === "array")
    return `varuint 数量 + ${describe(schema.item, `${path}[]`)} × 数量`;
  if (schema.kind === "map")
    return `varuint 数量 + (${describe(schema.key, `${path}.key`)}, ${describe(schema.value, `${path}.value`)}) × 数量`;
  if (schema.kind === "enum")
    return `u8 枚举：${schema.values.map((value, index) => `${index}=${value}`).join("，")}`;
  if (schema.kind === "struct") {
    if (seen.has(schema)) return `记录 ${seen.get(schema)}`;
    seen.set(schema, path);
    const slot = blocks.length;
    blocks.push("");
    const rows = schema.fields.map(
      ([name, field]) => `| ${name} | ${describe(field, `${path}.${name}`)} |`,
    );
    const optionalNames = schema.fields
      .filter(([, field]) => field.kind === "optional")
      .map(([name], index) => `${index}=${name}`);
    blocks[slot] = `## ${path}\n\n${optionalNames.length ? `起始为 ${optionalMaskKind(optionalNames.length)} 可选字段掩码：${optionalNames.join("，")}。\n\n` : ""}| 字段（写入顺序） | 编码 |\n|---|---|\n${rows.join("\n")}\n`;
    return `记录 ${path}`;
  }
  if (schema.kind === "string") return "varuint 段内字符串序号";
  if (schema.kind === "uint") return "varuint 非负安全整数";
  if (schema.kind === "baseStat") return "u8 类型：0=main，1=sub，2=后接 f64";
  if (schema.kind === "bool") return "u8：0=false，1=true";
  return schema.kind;
}
describe(containerHeaderSchema, "CONTAINER_HEADER（magic 之后）");
describe(containerEntrySchema, "CONTAINER_ENTRY");
const schemas = [
  metadataSchema,
  jobsSchema,
  foodsSchema,
  materiaSchema,
  syncSectionSchema,
  itemLevelCapsSectionSchema,
  equipmentCapsSchema,
  characterStatsSchema,
  levelFormulasSchema,
];
schemas.forEach((schema, index) => describe(schema, SECTION_NAMES[index]));
describe(gear.gearRecordHeaderSchema, "GEAR_RECORD_HEADER");
describe(gear.gearGroupDescriptorSchema, "GEAR_GROUP_DESCRIPTOR");
describe(gear.gearDirectoryEntrySchema, "GEAR_DIRECTORY_ENTRY");
describe(gear.mainStatIndexHeaderSchema, "GEAR_MAIN_STAT_INDEX_HEADER");
for (const [name, schema] of [
  ["GEAR_STRING_LENGTHS（名称池和获取途径池各一份）", gear.gearStringLengthsSchema],
  ["GEAR_STAT_MASK_DICTIONARY", gear.gearStatMaskDictionarySchema],
  ["GEAR_JOB_COMBINATION_DICTIONARY", gear.gearJobCombinationDictionarySchema],
]) {
  const description = describe(schema, name);
  blocks.push(`## ${name}\n\n${description}。\n`);
}
const content = `<!-- Generated by npm run data:format. DO NOT EDIT. -->\n# 运行时二进制字段（格式 ${FORMAT_VERSION}）\n\n字段定义来源为 src/data/binary 中的 TypeScript Schema；本文件由脚本生成。整数均为 little-endian。段编号依次为 ${SECTION_NAMES.map((name, index) => `${index + 1}=${name}`).join("，")}。\n\n每个非装备段先保存字符串表（varuint 字符串数，每个字符串为 varuint UTF-8 字节数及字节），随后保存该段根记录。可选字段按 Schema 中的顺序占用掩码位，未定义位必须为零。map 的键只允许 Schema 定义的枚举或数值，不写入对象字段名。\n\n${blocks.join("\n")}\n装备槽位代码：${gear.SLOT_NAMES.join(", ")}。\n\n装备属性位顺序：${gear.STAT_NAMES.join(", ")}。\n\n自定义属性代码：${gear.CUSTOM_STAT_NAMES.join(", ")}。\n\n物理组顺序：${gear.PHYSICAL_GROUPS.join(", ")}。\n\n装备 flags：${Object.entries(
  gear.GEAR_RECORD_FLAGS,
)
  .map(([key, value]) => `${key}=${value}`)
  .join(", ")}。\n`;
const output = new URL(
  "../docs/generated/运行时二进制字段.md",
  import.meta.url,
);
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== content)
    throw new Error("二进制字段文档过期，请运行 npm run data:format");
  console.log("二进制字段文档与 Schema 一致。");
} else {
  await mkdir(fileURLToPath(new URL(".", output)), { recursive: true });
  await writeFile(output, content, "utf8");
  console.log(`Generated ${fileURLToPath(output)}`);
}
